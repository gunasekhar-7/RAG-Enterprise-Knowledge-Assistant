"""Base abstract class and common utilities for all document parsers."""

import re
from abc import ABC, abstractmethod

from app.ingestion.models import DocumentMetadata, ExtractedPage


class BaseParser(ABC):
    """Abstract interface that all document format parsers must implement."""

    @abstractmethod
    def parse(self, content: bytes, metadata: DocumentMetadata) -> tuple[list[ExtractedPage], dict]:
        """Parses document bytes into a sequence of extracted pages and extracted metadata.

        Args:
            content: Raw file bytes.
            metadata: Initial metadata generated by FileValidator.

        Returns:
            A tuple of:
                1. List of ExtractedPage objects (preserving page/section numbering).
                2. Dictionary of extracted document-level metadata (e.g. title, author).

        Raises:
            CorruptDocumentError: if the file cannot be opened or parsed.
            DocumentParsingError: if an unexpected failure occurs during extraction.
        """
        pass

    @staticmethod
    def clean_text(text: str) -> str:
        """Sanitizes extracted raw text:

        - Replaces Windows \\r\\n and archaic \\r with \\n
        - Collapses redundant horizontal whitespaces
        - Collapses 3+ newlines down to 2 newlines (preserves paragraph breaks)
        - Strips leading and trailing whitespace
        """
        if not text:
            return ""

        # Normalize line endings
        normalized = text.replace("\r\n", "\n").replace("\r", "\n")

        # Remove null bytes or non-printable control chars (except tabs and newlines)
        normalized = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]", "", normalized)

        # Collapse excessive blank lines
        normalized = re.sub(r"\n{3,}", "\n\n", normalized)

        # Strip trailing whitespace on each line
        lines = [line.strip() for line in normalized.split("\n")]
        return "\n".join(lines).strip()
